#!/usr/bin/env python3
"""Bootstrap the two fixed accounts the legacy E2E specs log in with.

The specs create their own drafts, experiments and runs through the API; the
only thing they cannot create is their own login, because they hardcode the
emails `user_a_test@example.com` / `user_b_test@example.com` and read the
passwords from `ACCEPTANCE_PASSWORD_A` / `ACCEPTANCE_PASSWORD_B`. Without a
seed, "fix the origin and the spec runs" is simply not true.

This script talks to the running backend's public auth API, exactly as the CI
workflow does, and adds nothing to the product: no fixed account in application
code, no entitlement, no admin flag.

Isolation and safety:
  - refuses to run without --confirm-disposable, because it writes two user rows;
  - passwords are generated per run with `secrets` and written to a mode-600
    file; they are never printed, never passed on a command line, never logged;
  - it never deletes or edits an existing user: if the account already exists
    and the recorded password does not authenticate, it stops with instructions
    instead of resetting anything;
  - teardown is the disposable stack's own `docker compose … down -v`, which
    removes the database those rows live in. Nothing here targets a shared
    runtime, and the script does not know how to delete an account.

Usage:
  backend/scripts/seed_e2e_accounts.py --confirm-disposable
  backend/scripts/seed_e2e_accounts.py --confirm-disposable --backend-url http://127.0.0.1:8099
  backend/scripts/seed_e2e_accounts.py --dry-run

Exit: 0 seeded or already usable, 2 usage/precondition, 3 backend unreachable,
      4 account exists but the recorded password does not work,
      5 post-seed contract check failed.
"""

import argparse
import json
import os
import secrets
import sys
import tempfile
import urllib.error
import urllib.request
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[2]
DEFAULT_OUT = REPO_ROOT / ".local" / "e2e-accounts.env"

ACCOUNTS = (
    {
        "email": "user_a_test@example.com",
        "display_name": "User A",
        "env_key": "ACCEPTANCE_PASSWORD_A",
    },
    {
        "email": "user_b_test@example.com",
        "display_name": "User B",
        "env_key": "ACCEPTANCE_PASSWORD_B",
    },
)


def call(backend_url, path, payload=None, token=None, timeout=15):
    """Return (status, body). Raises URLError only when the backend is unreachable."""
    data = None if payload is None else json.dumps(payload).encode()
    request = urllib.request.Request(backend_url + path, data=data, method="POST" if data else "GET")
    if data is not None:
        request.add_header("Content-Type", "application/json")
    if token:
        request.add_header("Authorization", f"Bearer {token}")
    try:
        with urllib.request.urlopen(request, timeout=timeout) as response:
            raw = response.read().decode() or "{}"
            return response.status, json.loads(raw)
    except urllib.error.HTTPError as exc:
        raw = exc.read().decode() or "{}"
        try:
            body = json.loads(raw)
        except ValueError:
            body = {"detail": raw[:200]}
        return exc.code, body


def read_env_file(path):
    values = {}
    if not path.exists():
        return values
    for line in path.read_text().splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        values[key.strip()] = value.strip()
    return values


def write_env_file(path, values):
    path.parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=".accounts-")
    try:
        with os.fdopen(fd, "w") as handle:
            handle.write(
                "# Generated by backend/scripts/seed_e2e_accounts.py.\n"
                "# Disposable test accounts only. Do not commit; do not reuse elsewhere.\n"
            )
            for key, value in values.items():
                handle.write(f"{key}={value}\n")
        os.chmod(tmp, 0o600)
        os.replace(tmp, path)
    except BaseException:
        Path(tmp).unlink(missing_ok=True)
        raise
    os.chmod(path, 0o600)


def login(backend_url, email, password):
    status, body = call(
        backend_url, "/api/auth/login", {"email": email, "password": password}
    )
    if status == 200 and body.get("access_token"):
        return body["access_token"]
    return None


def me(backend_url, token):
    status, body = call(backend_url, "/api/auth/me", token=token)
    return body if status == 200 else None


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Create the two legacy E2E accounts on a disposable backend."
    )
    parser.add_argument(
        "--backend-url",
        default=os.environ.get("E2E_BACKEND_BASE") or os.environ.get("ALETHRA_BACKEND_URL") or "http://127.0.0.1:8001",
        help="running backend origin (default: %(default)s)",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path(os.environ.get("ALETHRA_E2E_ACCOUNTS_FILE") or DEFAULT_OUT),
        help="credential file to write, mode 600 (default: .local/e2e-accounts.env)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="print what would happen; no network call, no file written",
    )
    parser.add_argument(
        "--confirm-disposable",
        action="store_true",
        help="acknowledge that this creates two user rows on a disposable backend",
    )
    args = parser.parse_args(argv)

    backend_url = args.backend_url.rstrip("/")
    out_path = args.out if args.out.is_absolute() else (REPO_ROOT / args.out)

    if not args.dry_run and not args.confirm_disposable:
        print(
            "refusing: this writes two user rows; re-run with --confirm-disposable "
            "against a disposable backend",
            file=sys.stderr,
        )
        return 2

    if args.dry_run:
        print("dry run: no network call, no file written")
        print(f"backend      : {backend_url}")
        print(f"credential   : {out_path}")
        for account in ACCOUNTS:
            print(f"would ensure: {account['email']} ({account['env_key']})")
        return 0

    try:
        status, _ = call(backend_url, "/health", timeout=5)
        if status != 200:
            print(f"refusing: {backend_url}/health returned {status}", file=sys.stderr)
            return 3
    except urllib.error.URLError as exc:
        print(f"refusing: cannot reach {backend_url} ({type(exc.reason).__name__})", file=sys.stderr)
        return 3

    previous = read_env_file(out_path)
    found = {}
    identities = {}

    for account in ACCOUNTS:
        email = account["email"]
        stored = previous.get(account["env_key"])

        if stored:
            token = login(backend_url, email, stored)
            if token:
                found[account["env_key"]] = stored
                identities[email] = me(backend_url, token)
                print(f"reused : {email} (recorded password still authenticates)")
                continue

        password = secrets.token_urlsafe(24)
        status, body = call(
            backend_url,
            "/api/auth/register",
            {
                "email": email,
                "password": password,
                "display_name": account["display_name"],
                "user_type": "individual",
            },
        )
        if status == 201:
            token = login(backend_url, email, password)
            if not token:
                print(f"FAILED: {email} was created but cannot log in", file=sys.stderr)
                return 5
            found[account["env_key"]] = password
            identities[email] = me(backend_url, token)
            print(f"created: {email}")
            continue

        if status == 400 and "already registered" in str(body.get("detail", "")).lower():
            print(
                f"FAILED: {email} already exists and no working password is recorded in "
                f"{out_path}. Use a fresh disposable database (stack down -v), or point "
                "--out at the file that created it. This script never resets an account.",
                file=sys.stderr,
            )
            return 4

        print(f"FAILED: register {email} returned {status}", file=sys.stderr)
        return 5

    # Contract: both identities authenticate, are distinct, and are ordinary users.
    for email in ("user_a_test@example.com", "user_b_test@example.com"):
        identity = identities.get(email)
        if not identity:
            print(f"FAILED: /api/auth/me did not confirm {email}", file=sys.stderr)
            return 5
        if identity.get("email") != email or not identity.get("is_active"):
            print(f"FAILED: /api/auth/me returned an unexpected identity for {email}", file=sys.stderr)
            return 5
        if identity.get("is_admin"):
            print(f"FAILED: {email} is an admin; these specs need ordinary users", file=sys.stderr)
            return 5
    if identities["user_a_test@example.com"].get("id") == identities["user_b_test@example.com"].get("id"):
        print("FAILED: both accounts resolved to the same user id", file=sys.stderr)
        return 5

    write_env_file(
        out_path,
        {
            "ACCEPTANCE_PASSWORD_A": found["ACCEPTANCE_PASSWORD_A"],
            "ACCEPTANCE_PASSWORD_B": found["ACCEPTANCE_PASSWORD_B"],
        },
    )

    print(f"wrote  : {out_path} (mode 600, values not printed)")
    print("next   : set -a; . " + os.path.relpath(out_path, REPO_ROOT) + "; set +a")
    print(
        "         cd frontend && E2E_FRONTEND_BASE=<origin> E2E_BACKEND_BASE="
        + backend_url
        + " npx playwright test e2e/research-drafts.spec.ts e2e/method-review.spec.ts"
    )
    print("teardown: docker compose -p <project> -f docker-compose.e2e.yml down -v")
    return 0


if __name__ == "__main__":
    sys.exit(main())