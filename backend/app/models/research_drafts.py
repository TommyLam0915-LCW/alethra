"""Research draft models for Phase 2A mock research assistant."""
import uuid
from datetime import datetime
from sqlalchemy import (
    Column,
    String,
    Text,
    ForeignKey,
    DateTime,
    JSON,
    Enum as SQLEnum,
)
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.orm import relationship
import enum

from ..database import Base
from app.lib.timeutil import utcnow


class DraftStatus(str, enum.Enum):
    """Draft lifecycle status."""
    DRAFT = "draft"
    PENDING_REVIEW = "pending_review"
    ACCEPTED = "accepted"
    REJECTED = "rejected"


class ResearchDraft(Base):
    """Research draft generated by mock research assistant."""
    __tablename__ = "research_drafts"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    user_id = Column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=False, index=True)
    experiment_id = Column(UUID(as_uuid=True), ForeignKey("experiments.id"), nullable=True, index=True)
    # Traceability: set when this draft was proposed by the personal AI.
    source_conversation_id = Column(
        UUID(as_uuid=True), ForeignKey("ai_conversations.id"), nullable=True, index=True
    )

    title = Column(String(500), nullable=False)
    hypothesis = Column(Text, nullable=True)
    falsification_criteria = Column(Text, nullable=True)
    strategy_template = Column(String(100), nullable=True)
    asset_symbol = Column(String(50), nullable=True)
    benchmark_symbol = Column(String(50), nullable=True)
    initial_cash = Column(String(50), nullable=True)
    commission_rate = Column(String(50), nullable=True)
    slippage_rate = Column(String(50), nullable=True)
    research_rules = Column(JSON, nullable=True)

    status = Column(SQLEnum(DraftStatus), nullable=False, default=DraftStatus.DRAFT)
    assistant_questions = Column(JSON, nullable=True)
    assistant_responses = Column(JSON, nullable=True)

    created_at = Column(DateTime, default=utcnow, nullable=False)
    updated_at = Column(DateTime, default=utcnow, onupdate=utcnow, nullable=False)

    revisions = relationship("ResearchDraftRevision", back_populates="draft", cascade="all, delete-orphan")
    audit_events = relationship("ResearchDraftAuditEvent", back_populates="draft", cascade="all, delete-orphan")


class ResearchDraftRevision(Base):
    """Revision history for research drafts."""
    __tablename__ = "research_draft_revisions"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    draft_id = Column(UUID(as_uuid=True), ForeignKey("research_drafts.id"), nullable=False, index=True)
    revision_number = Column(String(50), nullable=False)

    title = Column(String(500), nullable=True)
    hypothesis = Column(Text, nullable=True)
    falsification_criteria = Column(Text, nullable=True)
    strategy_template = Column(String(100), nullable=True)
    asset_symbol = Column(String(50), nullable=True)
    benchmark_symbol = Column(String(50), nullable=True)
    initial_cash = Column(String(50), nullable=True)
    commission_rate = Column(String(50), nullable=True)
    slippage_rate = Column(String(50), nullable=True)
    research_rules = Column(JSON, nullable=True)

    status = Column(SQLEnum(DraftStatus), nullable=False)
    assistant_questions = Column(JSON, nullable=True)
    assistant_responses = Column(JSON, nullable=True)

    created_at = Column(DateTime, default=utcnow, nullable=False)

    draft = relationship("ResearchDraft", back_populates="revisions")


class ResearchDraftAuditEvent(Base):
    """Audit events for research draft operations."""
    __tablename__ = "research_draft_audit_events"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    draft_id = Column(UUID(as_uuid=True), ForeignKey("research_drafts.id"), nullable=False, index=True)
    user_id = Column(UUID(as_uuid=True), ForeignKey("users.id"), nullable=False, index=True)

    event_type = Column(String(100), nullable=False)
    event_data = Column(JSON, nullable=True)
    created_at = Column(DateTime, default=utcnow, nullable=False)

    draft = relationship("ResearchDraft", back_populates="audit_events")
